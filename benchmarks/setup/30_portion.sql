-- Model-output: Claude Fable 5
-- Scenario 4 table: application-time period + FOR PORTION OF view.  A portion
-- update of [400,600) on a [0,1000) row splits it into three rows: two slice
-- INSERTs plus the central UPDATE, all through update_portion_of().
--
-- The identity primary key is stripped from the slices and regenerated on
-- both 1.2 and 7.0.0 (it has a default), so the same statement is valid on
-- both sides.
CREATE TABLE bench.portion (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    value integer NOT NULL,
    note text,
    valid_from integer NOT NULL,
    valid_to integer NOT NULL
);
SELECT periods.add_period('bench.portion', 'valid_time', 'valid_from', 'valid_to');
SELECT periods.add_for_portion_view('bench.portion', 'valid_time');
INSERT INTO bench.portion (value, note, valid_from, valid_to)
SELECT 0, 'row ' || i, 0, 1000 FROM generate_series(1, 5000) AS i;

-- The pgbench scripts hardcode the view name; fail loudly if it ever changes.
DO $$
BEGIN
    IF pg_catalog.to_regclass('bench.portion__for_portion_of_valid_time') IS NULL THEN
        RAISE EXCEPTION 'portion view name changed; update benchmarks/t/portion_update.sql';
    END IF;
END$$;

VACUUM ANALYZE bench.portion;
